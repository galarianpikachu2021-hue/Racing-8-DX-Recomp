# Compiles the fork's FSR 1 shaders (AMD FidelityFX Super Resolution 1, MIT license) to SPIR-V and prints
# fsr1_spv.h for suyu_cmd/native_gpu. The sources are the suyu/yuzu present shaders, fp32 path:
#   video_core/host_shaders/vulkan_fidelityfx_fsr.vert, ..._easu_fp32.frag, ..._rcas_fp32.frag
#   tools/make-fsr1-shaders.sh <suyu fork root> > <fork>/src/suyu_cmd/native_gpu/fsr1_spv.h
set -euo pipefail
root="${1:?usage: $0 <suyu fork root>}"
hs="$root/src/video_core/host_shaders"
inc=(-I"$hs" -I"$root/externals/FidelityFX-FSR/ffx-fsr")
tmp="$(mktemp -d)"
glslc "${inc[@]}" -fshader-stage=vert "$hs/vulkan_fidelityfx_fsr.vert" -o "$tmp/v.spv"
glslc "${inc[@]}" -fshader-stage=frag "$hs/vulkan_fidelityfx_fsr_easu_fp32.frag" -o "$tmp/e.spv"
glslc "${inc[@]}" -fshader-stage=frag "$hs/vulkan_fidelityfx_fsr_rcas_fp32.frag" -o "$tmp/r.spv"
echo "// SPDX-License-Identifier: GPL-3.0-or-later"
echo "// FSR 1 shaders: AMD FidelityFX Super Resolution (c) 2021 Advanced Micro Devices, Inc., MIT license, via the"
echo "// suyu/yuzu present shaders. Generated by kart-recomp/tools/make-fsr1-shaders.sh; do not edit."
echo "#pragma once"
echo "#include <cstdint>"
echo "namespace KartOverlay {"
for pair in "v:kFsr1VertSpv" "e:kFsr1EasuSpv" "r:kFsr1RcasSpv"; do
  n="${pair%%:*}"; name="${pair##*:}"
  echo "constexpr uint32_t $name[] = {"
  python3 - "$tmp/$n.spv" <<'PY'
import struct, sys
d = open(sys.argv[1], 'rb').read()
w = struct.unpack('<%dI' % (len(d) // 4), d)
for i in range(0, len(w), 8):
    print('    ' + ','.join('0x%08x' % x for x in w[i:i+8]) + ',')
PY
  echo "};"
done
echo "} // namespace KartOverlay"
rm -rf "$tmp"
