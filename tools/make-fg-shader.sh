#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
# Compiles tools/fg-shaders/interp.comp to SPIR-V and prints fg_spv.h.
#   tools/make-fg-shader.sh > <suyu fork>/src/suyu_cmd/native_gpu/fg_spv.h
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
glslc "$here/fg-shaders/interp.comp" -o "$tmp/c.spv"
echo "// SPDX-License-Identifier: GPL-3.0-or-later"
echo "// Generated by kart-recomp/tools/make-fg-shader.sh; do not edit."
echo "#pragma once"
echo "#include <cstdint>"
echo "namespace KartFg {"
echo "constexpr uint32_t kInterpCompSpv[] = {"
python3 - "$tmp/c.spv" <<'PY'
import struct, sys
d = open(sys.argv[1], 'rb').read()
w = struct.unpack('<%dI' % (len(d) // 4), d)
for i in range(0, len(w), 8):
    print('    ' + ','.join('0x%08x' % x for x in w[i:i+8]) + ',')
PY
echo "};"
echo "} // namespace KartFg"
rm -rf "$tmp"
