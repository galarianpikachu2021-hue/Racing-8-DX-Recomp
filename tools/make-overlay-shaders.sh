#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
# Compiles tools/overlay-shaders/*.{vert,frag} to SPIR-V and prints overlay_spv.h.
#   tools/make-overlay-shaders.sh > <suyu fork>/src/suyu_cmd/native_gpu/overlay_spv.h
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
glslc "$here/overlay-shaders/overlay.vert" -o "$tmp/v.spv"
glslc "$here/overlay-shaders/overlay.frag" -o "$tmp/f.spv"
echo "// SPDX-License-Identifier: GPL-3.0-or-later"
echo "// Generated by kart-recomp/tools/make-overlay-shaders.sh; do not edit."
echo "#pragma once"
echo "#include <cstdint>"
echo "namespace KartOverlay {"
for n in v f; do
  name=$([ $n = v ] && echo kVertSpv || echo kFragSpv)
  echo "constexpr uint32_t $name[] = {"
  python3 - "$tmp/$n.spv" <<'PY'
import struct, sys
d = open(sys.argv[1], 'rb').read()
w = struct.unpack('<%dI' % (len(d) // 4), d)
for i in range(0, len(w), 8):
    print('    ' + ','.join('0x%08x' % x for x in w[i:i+8]) + ',')
PY
  echo "};"
done
echo "} // namespace KartOverlay"
rm -rf "$tmp"
