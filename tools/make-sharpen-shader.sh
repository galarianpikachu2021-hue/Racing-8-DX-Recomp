#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
# Compiles tools/sharpen-shaders/sharpen.comp and prints sharpen_spv.h for suyu_cmd/native_gpu.
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
glslc -fshader-stage=comp "$here/sharpen-shaders/sharpen.comp" -o "$tmp/s.spv"
echo "// SPDX-License-Identifier: GPL-3.0-or-later"
echo "// Sharpening compute shader. Generated by kart-recomp/tools/make-sharpen-shader.sh; do not edit."
echo "#pragma once"
echo "#include <cstdint>"
echo "namespace KartOverlay {"
echo "constexpr uint32_t kSharpenCompSpv[] = {"
python3 - "$tmp/s.spv" <<'PY'
import struct, sys
d = open(sys.argv[1], 'rb').read()
w = struct.unpack('<%dI' % (len(d) // 4), d)
for i in range(0, len(w), 8):
    print('    ' + ','.join('0x%08x' % x for x in w[i:i+8]) + ',')
PY
echo "};"
echo "} // namespace KartOverlay"
rm -rf "$tmp"
