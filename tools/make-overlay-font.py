"""Writes overlay_font.h: an 8-bit glyph atlas (ASCII 32..126, plus a solid cell at 95) for the in-game overlay menu.

    tools/make-overlay-font.py [font.ttf] > suyu_cmd/native_gpu/overlay_font.h

The default font is DejaVu Sans Mono (Bitstream Vera / DejaVu license: free to embed, keep the notice).
Cells are 8x16 layout units drawn at 4x (32x64 texels), 16 columns x 6 rows, so the atlas is 512x384: sharp at any
scale (the menu scales smoothly with the output height).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/TTF/DejaVuSansMono.ttf"
TEX = 4  # texels per layout unit
CW, CH, COLS, ROWS = 8 * TEX, 16 * TEX, 16, 6
font = ImageFont.truetype(path, 13 * TEX)
atlas = Image.new("L", (CW * COLS, CH * ROWS), 0)
draw = ImageDraw.Draw(atlas)
BASELINE = 12 * TEX  # leaves 4 units below for descenders
for code in range(32, 127):
    i = code - 32
    cell = Image.new("L", (CW, CH), 0)  # drawn per cell, so a glyph can't spill into its neighbour
    ImageDraw.Draw(cell).text((0, BASELINE), chr(code), fill=255, font=font, anchor="ls")
    atlas.paste(cell, ((i % COLS) * CW, (i // COLS) * CH))
# Cell 95 (after '~') is solid white: filled rectangles sample it.
draw.rectangle([(15 * CW, 5 * CH), (16 * CW - 1, 6 * CH - 1)], fill=255)
data = list(atlas.tobytes())
print("// SPDX-License-Identifier: LicenseRef-DejaVu (glyph shapes: DejaVu Sans Mono, Bitstream Vera/DejaVu license)")
print("// Generated by kart-recomp/tools/make-overlay-font.py; do not edit.")
print("#pragma once\n#include <cstdint>\nnamespace KartOverlay {")
print(f"constexpr int kFontCellW = {CW // TEX}, kFontCellH = {CH // TEX}, kFontCols = {COLS}, kFontRows = {ROWS}, kFontTex = {TEX};")
print(f"constexpr int kFontAtlasW = {CW * COLS}, kFontAtlasH = {CH * ROWS};")
print("constexpr uint8_t kFontAtlas[] = {")
for i in range(0, len(data), 24):
    print("    " + ",".join(str(v) for v in data[i:i + 24]) + ",")
print("};\n} // namespace KartOverlay")
