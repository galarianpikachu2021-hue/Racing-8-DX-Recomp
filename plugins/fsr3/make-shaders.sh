# Compiles plugins/fsr3/shaders/*.comp to colorspace_spv.h (SPIR-V as C arrays).
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
echo "// SPDX-License-Identifier: GPL-3.0-or-later"
echo "// Generated by plugins/fsr3/make-shaders.sh; do not edit."
echo "#pragma once"
echo "#include <cstdint>"
for pair in "to_linear:kToLinearSpv" "from_linear:kFromLinearSpv" "combine:kCombineSpv"; do
  n="${pair%%:*}"; name="${pair##*:}"
  glslc -fshader-stage=comp "$here/shaders/$n.comp" -o "$tmp/$n.spv"
  echo "static const uint32_t $name[] = {"
  python3 - "$tmp/$n.spv" <<'PY'
import struct, sys
d = open(sys.argv[1], 'rb').read()
w = struct.unpack('<%dI' % (len(d) // 4), d)
for i in range(0, len(w), 8):
    print('    ' + ','.join('0x%08x' % x for x in w[i:i+8]) + ',')
PY
  echo "};"
done
rm -rf "$tmp"
