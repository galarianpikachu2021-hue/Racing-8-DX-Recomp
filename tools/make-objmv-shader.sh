# Compiles tools/mv-shaders/objmv.frag and prints objmv_spv.h for suyu_cmd/native_gpu:
#   tools/make-objmv-shader.sh > <fork>/src/suyu_cmd/native_gpu/objmv_spv.h
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
tmp="$(mktemp -d)"
glslc -fshader-stage=frag --target-env=vulkan1.3 "$here/mv-shaders/objmv.frag" -o "$tmp/f.spv"
echo "// SPDX-License-Identifier: GPL-3.0-or-later"
echo "// Per-object motion-vector fragment shader. Generated by kart-recomp/tools/make-objmv-shader.sh; do not edit."
echo "#pragma once"
echo "#include <cstdint>"
echo "namespace KartOverlay {"
echo "constexpr uint32_t kObjMvFragSpv[] = {"
python3 - "$tmp/f.spv" <<'PY'
import struct, sys
d = open(sys.argv[1], 'rb').read()
w = struct.unpack('<%dI' % (len(d) // 4), d)
for i in range(0, len(w), 8):
    print('    ' + ','.join('0x%08x' % x for x in w[i:i+8]) + ',')
PY
echo "};"
echo "} // namespace KartOverlay"
rm -rf "$tmp"
