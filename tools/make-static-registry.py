#!/usr/bin/env python3
"""Write recomp_registration.c and the recomp_*_v1.h markers for an exefs/ export.

suyu's exporter writes these only for the Windows "Build" format (game_export.cpp
~3405, write_registration). On Linux we still want suyu-cmd-static (one binary,
no .so), so this reproduces that output. Keep it in step with the C++ writer.

  python3 tools/make-static-registry.py <export>/usr/bin/aot_cache/exefs
"""
import os
import sys

root = sys.argv[1]
mods = [d for d in os.listdir(root)
        if os.path.exists(f"{root}/{d}/CMakeLists.txt") and os.path.exists(f"{root}/{d}/recomp_export.c")]
order = [m for m in ["rtld", "main"] + [f"subsdk{i}" for i in range(10)] + ["sdk"] if m in mods]
order += sorted(m for m in mods if m not in order)

abi = set()
for m in order:
    h = open(f"{root}/{m}/recomp_runtime.h", errors="replace").read()
    abi.add("6" if "#define RECOMP_IMAGE_ABI 6" in h else "other")
assert abi == {"6"}, f"expected all ABI 6 modules, got {abi}"

o = []
w = o.append
w("/* auto-generated by tools/make-static-registry.py - mirrors suyu game export */\n"
  "#include <stdint.h>\n\ntypedef void (*SuyuRecompBlockFn)(void*);\n\n")
for m in order:
    w(f"extern SuyuRecompBlockFn recomp_image_lookup_{m}(uint64_t);\n"
      f"extern unsigned recomp_image_guard_v2_{m}(unsigned);\n"
      f"extern unsigned recomp_image_abi_{m}(void);\n"
      f"extern void recomp_image_run_slice_{m}(void*);\n"
      f"extern void recomp_image_set_base_{m}(uint64_t);\n"
      f"extern uint64_t g_module_base_{m};\n")
w("\ntypedef struct {\n    const char* name;\n    SuyuRecompBlockFn (*lookup)(uint64_t);\n"
  "    void (*set_base)(uint64_t);\n    SuyuRecompBlockFn run_slice;\n"
  "    unsigned (*image_abi)(void);\n} SuyuRecompStaticModule;\n\n"
  "const SuyuRecompStaticModule* suyu_recomp_static_modules_v4(unsigned* count);\n"
  "int suyu_recomp_static_guard_v2(unsigned version);\n\nstatic const SuyuRecompStaticModule s_modules[] = {\n")
for m in order:
    w(f'    {{ "{m}", recomp_image_lookup_{m}, recomp_image_set_base_{m}, recomp_image_run_slice_{m}, recomp_image_abi_{m} }},\n')
w("};\n\nconst SuyuRecompStaticModule* suyu_recomp_static_modules_v4(unsigned* count) {\n"
  "    *count = (unsigned)(sizeof(s_modules) / sizeof(s_modules[0]));\n    return s_modules;\n}\n")
w("int suyu_recomp_static_guard_v2(unsigned version) {\n  int ready=version==2;\n")
for m in order:
    w(f"  if(recomp_image_guard_v2_{m}(0)!=2) ready=0;\n")
for m in order:
    w(f"  recomp_image_guard_v2_{m}(ready?2:0);\n")
w("  return ready;\n}\n\n")
# FM1
for m in order:
    w(f"extern unsigned recomp_image_features_{m}(void);\n"
      f"extern unsigned recomp_image_fastmem_v1_{m}(uint32_t, uint32_t, uint64_t, uint32_t, uint32_t);\n")
w("int suyu_recomp_static_fastmem_v1(uint32_t, uint32_t, uint64_t, uint32_t, uint32_t);\n"
  "int suyu_recomp_static_fastmem_v1(uint32_t page_bits, uint32_t stride_log2,\n"
  "                                  uint64_t pointer_mask, uint32_t off_table,\n"
  "                                  uint32_t off_limit) {\n  int ready=1;\n")
for m in order:
    w(f"  if(!(recomp_image_features_{m}()&1u) || recomp_image_fastmem_v1_{m}(page_bits,stride_log2,pointer_mask,off_table,off_limit)!=1) ready=0;\n")
w("  return ready;\n}\nunsigned suyu_recomp_static_features_v1(void);\n"
  "unsigned suyu_recomp_static_features_v1(void) {\n  unsigned f=0;\n")
for m in order:
    w(f"  f|=recomp_image_features_{m}();\n")
w("  return f;\n}\n")
# GG1
w("\ntypedef struct { uint32_t* word; const uint64_t* base; uint64_t code_lo, code_end; } SuyuRecompGuardGenModule;\n")
for m in order:
    w(f"extern uint32_t* recomp_image_guard_gen_v1_{m}(uint32_t, uint64_t*, uint64_t*, const uint64_t**);\n")
w("unsigned suyu_recomp_static_guard_gen_v1(uint32_t host_version,\n"
  "                                         SuyuRecompGuardGenModule* out,\n"
  "                                         unsigned max);\n"
  "unsigned suyu_recomp_static_guard_gen_v1(uint32_t host_version,\n"
  "                                         SuyuRecompGuardGenModule* out,\n"
  "                                         unsigned max) {\n  unsigned n=0;\n"
  f"  if(max<{len(order)}u) return 0;\n")
for m in order:
    w(f"  out[n].word=recomp_image_guard_gen_v1_{m}(host_version,&out[n].code_lo,&out[n].code_end,&out[n].base);\n"
      "  if(!out[n++].word) return 0;\n")
w("  return n;\n}\n\n")
# FPX1
for m in order:
    w(f"extern unsigned recomp_image_fpx_v1_{m}(uint32_t, uint32_t, uint64_t);\n")
w("unsigned suyu_recomp_static_fpx_v1(uint32_t off_fpcr, uint32_t off_fpsr,\n"
  "                                   uint64_t inhibit_bit);\n"
  "unsigned suyu_recomp_static_fpx_v1(uint32_t off_fpcr, uint32_t off_fpsr,\n"
  "                                   uint64_t inhibit_bit) {\n  unsigned r=0;\n")
for m in order:
    w(f"  if(!(recomp_image_features_{m}()&4u)) return 0;\n"
      f"  r=recomp_image_fpx_v1_{m}(off_fpcr,off_fpsr,inhibit_bit);\n  if(!r) return 0;\n")
w("  return r;\n}\n")

open(f"{root}/recomp_registration.c", "w").write("".join(o))
for name in ["abi_v4", "guard_v2", "fastmem_v1", "fpx_v1", "features_v1", "guard_gen_v1"]:
    open(f"{root}/recomp_{name}.h", "w").write("/* marker written by make-static-registry.py */\n")
print("modules:", order)
